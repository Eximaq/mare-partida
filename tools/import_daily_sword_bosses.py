"""Import approved actor PNGs and prepared special-effect PNGs without recompression."""
import argparse
import hashlib
import io
import json
from pathlib import Path
from zipfile import ZipFile
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
ACTOR_SHA='fa9244a4a913a16b62ca9c1e9688e8fe1310ac566ac492dcb31038e2732352e8'
IDS=('daily-mihawk','daily-shanks','daily-ryuma-alive','daily-oden','daily-rayleigh','daily-zoro','daily-shiki')
ACTIONS=('idle','walk','attack','special','hurt')
DIRS=('south','north','east','west')
TRAVEL={'daily-mihawk','daily-shanks','daily-shiki'}
RADIAL={'daily-rayleigh','daily-shiki'}
sha=lambda v:hashlib.sha256(v).hexdigest()

def inspect(png,cell,frames,name):
    im=Image.open(io.BytesIO(png))
    if im.mode!='RGBA' or im.size!=(cell*frames,cell):
        raise ValueError(f'{name}: wrong format')
    bounds=[]
    for i in range(frames):
        a=im.crop((cell*i,0,cell*(i+1),cell)).getchannel('A')
        bounds.append(a.getbbox())
    if not bounds[frames//2] or any(b and not (0<b[0]<b[2]<cell and 0<b[1]<b[3]<cell) for b in bounds):
        raise ValueError(f'{name}: midpoint blank or clipped: {bounds}')
    return bounds

def import_all(approved,export):
    original=approved.read_bytes()
    if sha(original)!=ACTOR_SHA:
        raise ValueError('Approved actor package has changed')
    actors,effects,files={},{},{}
    specfile=(export/'daily-sword-boss-specials.json').read_bytes()
    spec=json.loads(specfile)
    if set(spec['actors'])!=set(IDS) or spec['anchor']!=[96,96] or spec['frames']!=6 or spec['frameSize']!=192:
        raise ValueError('Special-effect contract differs')
    with ZipFile(io.BytesIO(original)) as z:
        if z.testzip() is not None:
            raise ValueError('Corrupt actor package')
        m=json.loads(z.read('manifest.json'))
        if set(m['actors'])!=set(IDS) or m['anchor']!=[128,213]:
            raise ValueError('Actor set or pivot changed')
        for key in IDS:
            row=m['actors'][key]; clips={}
            for action in ACTIONS:
                clips[action]={}
                for direction in DIRS:
                    c=row['clips'][action][direction]
                    png=z.read(c['path'])
                    bounds=inspect(png,256,4,c['path'])
                    if sha(png)!=c['sha256'] or bounds!=[tuple(x) for x in c['bounds']] or any(not b for b in bounds):
                        raise ValueError(f"Approved clip metadata mismatch: {c['path']}")
                    asset=f'assets/sprites-combat-v2/{key}/{action}-{direction}.png'
                    files[asset]=png
                    clips[action][direction]=dict(image=asset,anchor=m['anchor'],size=256,frames=4,bounds=bounds,
                        fps=4000/sum(c['durationsMs']),loop=c['loop'],frame_durations_ms=c['durationsMs'],png_sha256=c['sha256'],
                        **({'impact_frame':2} if action in ('attack','special') else {}))
            actors[key]=dict(name=row['name'],specialLabel=row['specialLabel'],monster=True,directionalHurt=True,
                worldHeight=row['worldHeight'],legacyHeight=row['worldHeight'],availability='unassigned',clips=clips)
            effects[key]={}
            for effect in ('travel','impact') if key in TRAVEL else ('impact',):
                asset=f'assets/vfx/daily-sword-bosses/{key}/{effect}.png'
                png=(export/asset).read_bytes()
                proof=spec['actors'][key]['art'][effect]
                if proof['path']!=asset or proof['sha256']!=sha(png):
                    raise ValueError(f'{asset}: source manifest digest/route mismatch')
                bounds=inspect(png,192,6,asset)
                files[asset]=png
                effects[key][effect]=dict(image=asset,anchor=[96,96],size=192,frames=6,bounds=bounds,png_sha256=sha(png),
                    nativeFacing='radial' if key in RADIAL and effect=='impact' else 'fixed' if key=='daily-shiki' else 'east')
    if len(files)!=150:
        raise ValueError('Expected 140 actor strips + ten VFX strips')
    for path,png in files.items():
        out=ROOT/path;out.parent.mkdir(parents=True,exist_ok=True);out.write_bytes(png)
    (ROOT/'daily-sword-boss-specials.json').write_bytes(specfile)
    src="'use strict';\n// Generated by tools/import_daily_sword_bosses.py.\n((root)=>{\nconst data="+json.dumps(
        dict(actorArchiveSha256=ACTOR_SHA,actors=actors,effects=effects,specials=spec['actors']),ensure_ascii=False,separators=(',',':'))+";\n"
    src+="const registry=root.MareSpriteCombatV2Data;\nfor(const [id,entry] of Object.entries(data.actors)){\n if(registry&&!Object.hasOwn(registry,id))registry[id]=entry;\n}\nroot.MareDailySwordBossArtData=data;\nif(typeof module!=='undefined')module.exports=data;\n})(globalThis);\n"
    (ROOT/'daily-sword-boss-art-data.js').write_text(src,encoding='utf-8')
    print('Imported 140 approved actor strips and ten separate effects.')
if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('actors',type=Path);p.add_argument('effects_export',type=Path);args=p.parse_args()
    import_all(args.actors,args.effects_export)
