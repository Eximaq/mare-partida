#!/usr/bin/env python3
"""Register the approved CP9 action strips without changing pixels or spawn lists."""
import hashlib
import io
import json
import sys
from pathlib import Path
from zipfile import ZipFile
from PIL import Image, ImageChops, ImageOps
ROOT = Path(__file__).resolve().parents[1]
SRC = Path(sys.argv[1])
DIRS = dict(south="sul", north="norte", east="leste", west="oeste")
ACTIONS = dict(idle="repouso", walk="caminhada", hurt="dano", attack="ataque")
FPS = dict(idle=4, walk=8, hurt=12, attack=10)
PACKS = [
    ("CP9_Kaku_e_Rob_Lucci_4_direcoes.zip",[
        ("kaku","kaku/humano",106,False),("kaku-zoan","kaku/zoan",116,True),
        ("rob-lucci","lucci/humano",110,False),("rob-lucci-zoan","lucci/zoan",126,True)]),
    ("CP9_Kalifa_e_Fukurou_4_direcoes.zip",[
        ("kalifa","kalifa",104,True),("fukurou","fukurou",98,True)]),
    ("CP9_Jabra_e_Blueno_4_direcoes.zip",[
        ("jabra","jabra-humano",108,False),("jabra-zoan","jabra-zoan",122,True),
        ("blueno","blueno",116,True)]),
]

def mirror(im):
    r=Image.new("RGBA",im.size)
    r.alpha_composite(ImageOps.mirror(im),(1,0))
    return r

def boxes(im):
    return [im.crop((128*i,0,128*(i+1),128)).getchannel("A")
            .point([0]*32+[255]*224).getbbox() for i in range(4)]

def main():
    out={}
    pngs=0
    for filename, entries in PACKS:
        archive=SRC/filename
        digest=hashlib.sha256(archive.read_bytes()).hexdigest()
        with ZipFile(archive) as z:
            assert z.testzip() is None
            for key,folder,height,can_attack in entries:
                clips={}
                for action,label in ACTIONS.items():
                    if action == "attack" and not can_attack:
                        continue
                    clips[action]={}
                    original={}
                    for direction,source in DIRS.items():
                        data=z.read(f"{folder}/{source}/{label}.png")
                        im=Image.open(io.BytesIO(data))
                        assert im.mode=="RGBA" and im.size==(512,128)
                        b=boxes(im)
                        assert all(p and min(p[0],p[1],128-p[2],128-p[3])>=3 for p in b)
                        original[direction]=im
                        target=Path(f"assets/sprites-combat-v2/{key}/{action}-{direction}.png")
                        (ROOT/target).parent.mkdir(parents=True,exist_ok=True)
                        (ROOT/target).write_bytes(data)
                        clips[action][direction]=dict(image=target.as_posix(),size=128,frames=4,
                            fps=FPS[action],loop=action in ("idle","walk"),anchor=[64,108],bounds=b,
                            **({"impact_frame":2} if action=="attack" else {}),
                            **({"mirrored_from":"east"} if direction=="west" else {}),
                            png_sha256=hashlib.sha256(data).hexdigest())
                        pngs+=1
                    for i in range(4):
                        box=(128*i,0,128*(i+1),128)
                        assert ImageChops.difference(mirror(original["east"].crop(box)),original["west"].crop(box)).getbbox(alpha_only=False) is None
                out[key]={"id":key,"source":"Approved generated CP9 sprite pack","archive_sha256":digest,
                    "monster":True,"directionalHurt":True,"legacyHeight":height,"worldHeight":height,"clips":clips}
    assert pngs==132
    body=json.dumps(out,ensure_ascii=False,separators=(",",":"))
    (ROOT/"cp9-sprites.js").write_text("'use strict';\n// Generated by tools/import_cp9_sprites.py.\n"
        +"((root)=>{const data="+body+";root.MareCp9SpriteData=data;if(typeof module!=='undefined')module.exports=data;})(globalThis);\n")
    print("Registered",pngs,"unmodified transparent action strips")

if __name__=="__main__": main()
