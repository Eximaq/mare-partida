"""Import authored Thriller Bark strips from the three approved sprite packs, byte for byte."""
import argparse
import hashlib
import io
import json
from pathlib import Path
import zipfile
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
PACKS = (
    ('Perona_e_Absalom', '9a376058ca5bd4076a1ff8c92289fefbf07b8f914d43c0cd35e30bb655bd7e66', [('absalom', 'Absalom', 128, 108, 108), ('perona', 'Perona', 128, 108, 102)]),
    ('Ryuma_e_Oars', '588a6c141d366294626ccaac4a44bca31ed8265122ea459793f381862cfd933a', [('ryuma', 'Ryuma', 128, 108, 110), ('oars', 'Oars', 256, 220, 216)]),
    ('Gecko_Moria', '7b93218e3080d855960c255d429cebb246e732526563c0cdc5396b465fefee2d', [('gecko-moria', 'Gecko Moria', 192, 162, 154)]),
)
DIRECTIONS = dict(south='sul', north='norte', east='leste', west='oeste')
ACTIONS = dict(idle='repouso', walk='caminhada', hurt='dano', attack='ataque')
sha256 = lambda data: hashlib.sha256(data).hexdigest()
entries = {}
files = {}
def validate_strip(image, cell):
    if image.mode != 'RGBA' or image.size != (4*cell, cell):
        raise ValueError(f'Invalid strip format: {image.mode}, {image.size}')
    frames = [image.crop((i*cell, 0, (i+1)*cell, cell)) for i in range(4)]
    for frame in frames:
        bounds = frame.getchannel('A').getbbox()
        if not bounds or not (0 < bounds[0] < bounds[2] < cell and 0 < bounds[1] < bounds[3] < cell):
            raise ValueError(f'Clipped or empty frame: {bounds}')
    if len({frame.tobytes() for frame in frames}) < 3:
        raise ValueError('Repeated pose')
    return frames

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('pack_directory', type=Path)
    args=parser.parse_args()
    for pack, expected_hash, monsters in PACKS:
        archive=args.pack_directory/f'Thriller_Bark_{pack}_4_direcoes.zip'
        dig=sha256(archive.read_bytes())
        if dig != expected_hash:
            raise ValueError(f'Unexpected archive bytes: {archive.name} {dig}')
        with zipfile.ZipFile(archive) as z:
            if z.testzip() is not None:
                raise ValueError(f'CRC did not pass: {archive.name}')
            for key, name, cell, feet, height in monsters:
                zkey='moria' if key=='gecko-moria' else key
                clips={}
                for act, alias in ACTIONS.items():
                    clips[act]={}
                    east=None
                    for direction, orient in DIRECTIONS.items():
                        png=z.read(f'{zkey}/{orient}/{alias}.png')
                        frames=validate_strip(Image.open(io.BytesIO(png)),cell)
                        if direction=='east':
                            east=frames
                        if direction=='west':
                            for original, reflected in zip(east,frames):
                                expected=Image.new('RGBA', (cell,cell))
                                expected.paste(ImageOps.mirror(original), (1,0))
                                if expected.tobytes()!=reflected.tobytes():
                                    raise ValueError(f'Mirror differs for {key}/{act}')
                        dest=f'assets/sprites-combat-v2/{key}/{act}-{direction}.png'
                        files[dest]=png
                        clips[act][direction]={'image':dest,'size':cell,'frames':4,'anchor':[cell//2,feet],
                          'bounds':[f.getchannel('A').getbbox() for f in frames],'png_sha256':sha256(png),
                          'fps': {'idle':4,'walk':8,'hurt':22.22222222222222,'attack':10}[act],
                          'loop':act in ('idle','walk'),**({'impact_frame':2} if act=='attack' else {}),
                          **({'mirrored_from':'east'} if direction=='west' else {})}
                entries[key]={'name':name,'source':archive.name,'archive_sha256':dig,'worldHeight':height,
                  'legacyHeight':height,'monster':True,'directionalHurt':True,'clips':clips}
    if len(entries)!=5 or len(files)!=80:
        raise ValueError('Invalid sprite count')
    for name, bytes_ in files.items():
        path=ROOT/name
        path.parent.mkdir(parents=True,exist_ok=True)
        path.write_bytes(bytes_)
    header="'use strict';\n// Generated by tools/import_thriller_sprites.py from the approved PNG packs.\n"
    script=header+"((root)=>{\nconst entries="+json.dumps(entries,ensure_ascii=False,separators=(',',':'))+";\n"
    script+="const registry=root.MareSpriteCombatV2Data;\nfor(const [id,entry] of Object.entries(entries)){\n if(registry&&!Object.hasOwn(registry,id))registry[id]=entry;\n}\nroot.MareThrillerSpriteData=entries;\nif(typeof module!=='undefined')module.exports=entries;\n})(globalThis);\n"
    (ROOT/'thriller-sprites.js').write_text(script,encoding='utf-8')
    print('Imported 80 authored directional strips.')

if __name__=='__main__':
    main()
