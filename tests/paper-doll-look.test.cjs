const assert=require('node:assert/strict');
const look=require('../paper-doll-look.js');
require('../paper-doll.js');require('../paper-doll-assets.js');
const review=require('../paper-doll-review.js'),pack=require('../pixellab-pip-generations/paper-doll-navy-starter-20261023/review-pack.json');
const old={classId:'sword',factionId:'pirate',level:50,equipment:{},inventory:[{def:0}],gold:100};
assert.deepEqual(look.read(old),look.defaults);
assert.deepEqual(look.read({paperDollLook:{version:999,hair:'bald'}}),look.defaults);
assert.deepEqual(look.read({paperDollLook:{version:1,hair:'<script>',outfit:'../bad'}}),look.defaults);
assert.equal(look.apply(old,{version:1,hair:'bald',outfit:'base'}),null,'normal save must not opt into draft art');
const dev={...old,devSandbox:true},before=JSON.stringify(dev);
const next=look.apply(dev,{version:1,hair:'bald',outfit:'base',gold:9999});
assert.equal(JSON.stringify(dev),before);
assert.deepEqual(next,{...dev,paperDollLook:{version:1,hair:'bald',outfit:'base'}});
assert.deepEqual(review.appearance(pack,next).hidden,['weapon','hair','outfit']);
assert.deepEqual(review.appearance(pack,{...next,equipment:{coat:{def:6}}}).hidden,['weapon','hair']);
assert.equal(review.appearance(pack,{...next,zoanTransformed:true}),null);
assert.equal(look.apply(dev,{version:1,hair:'unknown',outfit:'navy'}),null);
assert.equal(look.apply(dev,{version:1,hair:'short-black',outfit:'navy'}).classId,'sword');
const html=look.render(dev,look.defaults,'<script>');
assert(!html.includes('<script>'));assert(html.includes('&lt;script&gt;'));
console.log('Paper Doll look: old/malformed saves, immutable DEV-only application, equipment precedence, Zoan and HTML escaping passed.');
