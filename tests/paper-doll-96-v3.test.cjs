const assert = require('node:assert/strict');
const rig = require('../tools/paper-doll-96-v3/rig.js');
const layers = require('../tools/paper-doll-96-v3/layers.js');

const point = (label, x, y, z_index = 0) => ({ label, x, y, z_index });
const old = [point('NECK', .5, .3), point('LEFT SHOULDER', .6, .3), point('LEFT ELBOW', .6, .5), point('LEFT ARM', .6, .7, -.5)];
const next = old.map(p => ({ ...p, x: p.label === 'LEFT ARM' ? .8 : p.x, y: p.label === 'LEFT ARM' ? .5 : p.y }));
const target = [point('NECK', .5, .4), point('LEFT SHOULDER', .65, .4), point('LEFT ELBOW', .65, .55), point('LEFT ARM', .65, .7)];
const snapshot = JSON.stringify({ old, next, target });
const result = rig.retarget(old, next, target);
assert.equal(JSON.stringify({ old, next, target }), snapshot, 'retargeting does not modify inputs');
const wrist = result.find(p => p.label === 'LEFT ARM');
assert.ok(Math.abs(wrist.x - .8) < 1e-9);
assert.ok(Math.abs(wrist.y - .55) < 1e-9);
assert.ok(result.every(p => Number.isInteger(p.z_index)), 'estimator fractional depth becomes integer order');
const shortPose = old.map(p => ({ ...p, y: p.label === 'LEFT ARM' ? .6 : p.y }));
const shortened = rig.retarget(old, shortPose, target).find(p => p.label === 'LEFT ARM');
assert.ok(Math.abs(shortened.y - .625) < 1e-9, 'projected limb shortening must survive retargeting');
assert.throws(() => rig.retarget(old, next.slice(1), target), /missing/i);
assert.equal(rig.frameAt({ frames: 8, fps: 8, loop: true }, 1000), 0);
assert.equal(rig.frameAt({ frames: 8, fps: 8, loop: false }, 1000), 7);
assert.equal(rig.frameAt({ frames: 8, fps: 8, loop: true }, 125), 1);
assert.throws(() => rig.frameAt({ frames: 0, fps: 8 }, 0));
assert.throws(() => rig.frameAt({ frames: 8, fps: 0 }, 0));
assert.throws(() => rig.frameAt({ frames: 8, fps: 8 }, Infinity));
assert.equal(rig.displayScale({ referenceHeight: 96 }), 1);
assert.equal(rig.displayScale({ referenceHeight: 48 }), 2);
const pieces = Object.fromEntries(layers.order.map(slot => [slot, `assets/test-${slot}.png`]));
assert.deepEqual(layers.visible(pieces, ['face', 'hair']).map(p => p.slot), ['body', 'pants', 'top']);
assert.equal(Object.keys(pieces).length, 5, 'hiding layers must not mutate selection');
const contract = { productionEnabled: false, frame: { width: 128, height: 128 }, pivot: { x: 64, y: 112 }, referenceHeight: 96, bodies: { female: { layers: { south: pieces } } } };
assert.equal(layers.validate(contract), true);
assert.throws(() => layers.validate({ ...contract, productionEnabled: true }));
assert.throws(() => layers.validate({ ...contract, bodies: { female: { layers: { south: { ...pieces, hair: '../private.png' } } } } }));
assert.throws(() => layers.validate({ ...contract, bodies: { female: { clips: { walk: { south: { modular: true, layers: { body: pieces.body } } } } } } }));
console.log('96px v3: retargeting, input preservation, depth, clock and fixed scale passed');
