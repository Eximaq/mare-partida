const assert=require('node:assert/strict');
const {create}=require('../combat-animation.js');
const clips={'combat-idle':{frames:4,fps:4},attack:{frames:8,fps:12,impact_frame:3},skill:{frames:12,fps:14,impact_frame:5},hurt:{frames:4,fps:14},death:{frames:8,fps:8}};
let hits=0;const a=create(clips);
a.step(.1,{inCombat:true});assert.equal(a.snapshot().action,'combat-idle');
a.step(.1,{moving:true,direction:'left'});assert.equal(a.snapshot().action,'walk');
assert(a.play('attack',{direction:'right',onImpact:()=>hits++}));
assert(!a.play('skill'));assert(!a.play('hurt'));
a.step(.2,{moving:true,direction:'back'});assert.equal(hits,0);assert.equal(a.snapshot().direction,'right');
a.step(.06);assert.equal(hits,1);a.step(.1);assert.equal(hits,1);
a.step(1,{inCombat:true});assert.equal(a.snapshot().action,'hurt');
a.step(1,{inCombat:true});assert.equal(a.snapshot().action,'combat-idle');
assert(a.play('skill',{onImpact:()=>hits++}));a.step(3);assert.equal(hits,2);assert(!a.locked());
assert(a.play('attack',{onImpact:()=>hits++}));assert(a.play('death'));
a.step(10,{moving:true});assert.equal(hits,2);assert.equal(a.snapshot().action,'death');assert(a.locked());assert.equal(a.snapshot().elapsed,1);
assert(!a.play('attack'));assert(!a.play('death'));
a.reset('back');assert.equal(a.snapshot().action,'idle');assert(!a.locked());
assert(a.play('hurt'));a.step(1);assert(!a.locked());
a.step(NaN);assert(Number.isFinite(a.snapshot().elapsed));
console.log('Combat animation: movement, action exclusion, impact exactly once, long frame, death cancellation/hold and reset passed.');
let northHits=0;const north=create({skill:{frames:12,fps:14,impact_frame:5,direction_impact_frames:{north:3}}});
north.play('skill',{direction:'back',onImpact:()=>northHits++});north.step(2/14);assert.equal(northHits,0);north.step(1/14+.001);assert.equal(northHits,1);
north.reset();north.play('skill',{direction:'front',onImpact:()=>northHits++});north.step(3/14+.001);assert.equal(northHits,1);north.step(2/14);assert.equal(northHits,2);
console.log('Direction-specific impact: corrected north uses frame 3; south retains frame 5.');
let heals=0;const support=create({'skill-1':{frames:8,fps:10,impact_frame:4,loop:false},death:{frames:8,fps:8,loop:false}});
assert(support.play('skill-1',{onImpact:()=>heals++}));support.step(.39);assert.equal(heals,0);support.step(.01);assert.equal(heals,1);support.step(2);assert.equal(heals,1);
support.play('skill-1',{onImpact:()=>heals++});support.play('death');support.step(2);assert.equal(heals,1,'death cancels a pending heal');
const directional=create({attack:{frames:8,fps:8,direction_frames:{north:4},direction_fps:{north:16},direction_impact_frames:{north:2}}});
directional.play('attack',{direction:'back'});assert.equal(directional.snapshot().duration,.25);directional.step(.26);assert(!directional.locked());
console.log('Class actions: delayed heal once, death cancellation and per-direction duration passed.');
