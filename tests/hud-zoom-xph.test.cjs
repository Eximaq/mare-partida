'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const engine=read('hud-telemetry.js'),game=read('game.js'),html=read('index.html'),css=read('hud-zoom-expedition.css'),build=read('tools/build_pages.py');
new vm.Script(game,{filename:'game.js'});
new vm.Script(engine,{filename:'hud-telemetry.js'});
const stats=require('../hud-telemetry.js');
let updates=0;
const zoom=stats.createZoom(()=>updates++);
assert.equal(zoom.value,1);
assert.equal(zoom.step(1),1.1);
assert.equal(zoom.set(12),1.8);
assert.equal(zoom.set(-10),.8);
assert.equal(zoom.reset(),1);
assert.equal(updates,4);
assert.equal(zoom.set(Number.NaN),1);
assert.equal(stats.duration(5),'00:05');
assert.equal(stats.duration(3661),'01:01:01');
assert.equal(stats.stats({scene:'hunt',elapsed:0,xp:100}).rate,null,'no misleading rate at 0 sec');
assert.equal(stats.stats({scene:'hunt',elapsed:19,xp:100}).rate,null,'wait for minimum 20 sec');
assert.equal(stats.stats({scene:'hunt',elapsed:60,xp:100}).rate,6000);
assert.equal(stats.stats({scene:'lobby',elapsed:60,xp:100}).active,false);
assert.equal(stats.stats({scene:'hunt',elapsed:240,xp:500,levelXP:34,neededXP:100}).progress,.34);
assert.equal(stats.stats({scene:'hunt',elapsed:60,xp:20,levelXP:180,neededXP:100}).progress,1);
assert.match(game,/const rect=canvas\.getBoundingClientRect\(\), zoom=worldZoom\.value/);
assert.match(game,/\(event\.clientX-rect\.left\)\*W\/rect\.width/,'canvas click scales with logical zoom');
assert.match(game,/\(event\.clientY-rect\.top\)\*H\/rect\.height/,'canvas click y scales with zoom');
assert.match(game,/canvas\.addEventListener\('wheel',/);
assert.match(game,/document\.querySelector\('\.dashboard'\)\.appendChild\(tracker\)/,'XP/h is independent from the journal');
assert.match(game,/session\.elapsed,xp:session\.xp/);
assert.match(game,/tracker\.hidden=!telemetry\.active/,'XP/h hidden in lobby');
assert.match(game,/if\(reward\.xp&&scene!=='hunt'\)/,'redundant XP popup removed only while hunting');
assert.ok(css.includes('#huntXpTracker.hunt-xp-tracker'));
assert.ok(css.includes('#worldCanvas {image-rendering:pixelated'));
assert.ok(html.includes('src="hud-telemetry.js"')&&html.includes('href="hud-zoom-expedition.css"'));
for(const f of ['hud-telemetry.js','hud-zoom-expedition.css'])assert.ok(build.includes("'"+f+"'"),'Pages should include '+f);

assert.match(game,/document\.addEventListener\('wheel'/,'Ctrl+wheel zoom prevention');
assert.doesNotMatch(game,/worldZoomControls/,'zoom buttons removed');
assert.match(game,/appendChild\(tracker\)/,'hunt tracker independent of journal');
console.log('Hunt XP panel independent; Ctrl+wheel browser zoom blocked; zoom controls removed');
