'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const get=f=>fs.readFileSync(path.join(__dirname,'..',f),'utf8');
const html=get('index.html'),js=get('game.js'),css=get('modes-menu.css'),build=get('tools/build_pages.py');
new vm.Script(js,{filename:'game.js'});
assert.match(html,/id="modesMenuTrigger"[^>]*data-modes-menu-trigger[^>]*aria-haspopup="menu"[^>]*aria-expanded="false"/);
assert.match(html,/id="modesQuickMenu"[^>]*class="character-quick-menu modes-quick-menu hidden"/);
assert.equal((html.match(/data-quick-mode="/g)||[]).length,2,'no unsupported modes added');
for(const mode of ['map','prison'])assert.ok(html.includes('data-quick-mode="'+mode+'"'),mode+' is directly accessible');
assert.ok(html.includes('aria-keyshortcuts="M"'));
assert.ok(html.includes('href="modes-menu.css"'));
assert.match(js,/function toggleModesMenu\(\)/);
assert.match(js,/function closeModesMenu\(restoreFocus=false\)/);
assert.match(js,/if\(panel==='modes'\)\{\s*if\(currentPanel\)closePanel\(\);\s*toggleModesMenu\(\);/);
assert.match(js,/openPanel\(quickMode\.dataset\.quickMode\)/);
assert.match(js,/if\(k==='m'\)\{openPanel\('modes'\);return;\}/);
assert.match(js,/if\(b\.hasAttribute\('data-modes-menu-trigger'\)\|\|b\.hasAttribute\('data-character-menu-trigger'\)\)return/,'no duplicate handler opens modal');
assert.match(js,/if\(!\$\('modesQuickMenu'\)\.classList\.contains\('hidden'\)\)/,'Esc closes Modes');
assert.match(js,/const activeQuickMenu=/,'shared keyboard navigation');
assert.match(js,/if\(navigation\.includes\(panel\)/,'existing voyage focus management retained');
assert.ok(css.includes('#mainMenu .modes-quick-menu'));
assert.ok(build.includes("'modes-menu.css'"));
console.log('Menu Modos: direct map/prison actions, keyboard navigation, escape, focus, CSS and Pages build OK');
